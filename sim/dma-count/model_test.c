// Executes the real dma_phys(), width_bytes() and dma_run() from ngage_dma.c.
// Only QEMU memory/IRQ/allocation dependencies are stubbed, not the transfer.
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef uint64_t hwaddr;
typedef struct { uint32_t regs[8][16]; FILE *log; } NGageDma;
#define MIN(a, b) ((a) < (b) ? (a) : (b))
#define MEMTXATTRS_UNSPECIFIED 0
#define NGAGE_IRQ_DMA(ch) (6 + (ch))
#define g_malloc malloc
static void release(void *p) { free(*(void **)p); }
#define g_autofree __attribute__((cleanup(release)))

static uint8_t memory[4096], expected[4096], stream[2048];
static unsigned cases, reads, writes, moved_read, moved_write;
static unsigned sw, dw, total, sa, da, kind;
static bool si, di;
static int address_space_memory, interrupt;
static void require(bool condition, const char *message)
{
    if (!condition) {
        fprintf(stderr, "FAIL donor DMA C case=%u read=%u written=%u budget=%u: %s\n",
                cases, moved_read, moved_write, total, message);
        exit(1);
    }
}
static unsigned ngage_guest_pc(void) { return 0; }
static void ngage_intc_set_source(int source, int level)
{
    require(source == 6, "unexpected interrupt source");
    interrupt = level;
}
static void address_space_read(void *space, hwaddr address, int attrs, void *data, size_t length)
{
    (void)space;
    (void)attrs;
    unsigned n = MIN(sw, total - moved_read);
    require(moved_read < total && length == n, "source extent exceeds byte budget");
    require(address == sa + (si ? moved_read : 0), "source address sequence");
    if (kind == 2) memcpy(data, stream + moved_read, length);
    else {
        require(address + length <= sizeof memory, "source address bounds");
        memcpy(data, memory + address, length);
    }
    moved_read += length;
    reads++;
}
static void address_space_write(void *space, hwaddr address, int attrs, const void *data, size_t length)
{
    (void)space;
    (void)attrs;
    unsigned n = MIN(dw, total - moved_write);
    require(moved_write < total && length == n, "destination extent exceeds byte budget");
    require(address == da + (di ? moved_write : 0), "destination address sequence");
    require(moved_write + length <= moved_read, "write consumed unread bytes");
    require(memcmp(data, stream + moved_write, length) == 0, "ordered write payload");
    if (kind != 1 && kind != 3) {
        require(address + length <= sizeof memory, "destination address bounds");
        memcpy(memory + address, data, length);
    }
    moved_write += length;
    writes++;
}

// Generated by run.sh directly from the maintained C source, without rewriting
// these functions. This is a focused unit test, not a complete QEMU build.
#include "dma_run.inc"

static void run_case(unsigned source_width, unsigned destination_width, unsigned units,
                     unsigned control, bool source_inc, bool destination_inc,
                     unsigned source_lane, unsigned destination_lane, unsigned fifo_kind)
{
    NGageDma state = {0};
    cases++;
    sw = source_width;
    dw = destination_width;
    si = source_inc;
    di = destination_inc;
    kind = fifo_kind;
    sa = kind == 2 ? 0x0c120624 : 256 + source_lane;
    da = kind == 1 ? 0x0c120624 : kind == 3 ? 0x0c121208 : 2048 + destination_lane;
    total = units * (control == 1 ? 2 : di ? sw : dw);
    reads = writes = moved_read = moved_write = 0;
    interrupt = 0;
    for (unsigned i = 0; i < sizeof memory; i++)
        memory[i] = expected[i] = (i * 29 + cases * 13 + i / 7) % 256;
    for (unsigned i = 0; i < total; i++)
        stream[i] = kind == 2 ? (i * 17 + 0x35) % 256 : memory[sa + (si ? i : i % sw)];
    if (kind != 1 && kind != 3)
        for (unsigned i = 0; i < total; i += dw)
            for (unsigned j = 0; j < dw && i+j < total; j++)
                expected[da + (di ? i : 0) + j] = stream[i+j];
    state.regs[0][0x08 / 4] = control;
    state.regs[0][0x14 / 4] = sa;
    state.regs[0][0x18 / 4] = si ? 4 : 0;
    state.regs[0][0x1c / 4] = sw * 8;
    state.regs[0][0x20 / 4] = kind == 1 ? 0x10120624 : kind == 3 ? 0x10121208 : da;
    state.regs[0][0x24 / 4] = di ? 4 : 0;
    state.regs[0][0x28 / 4] = dw * 8;
    state.regs[0][0x2c / 4] = units - 1;
    dma_run(&state, 0);
    require(interrupt == 1 && state.regs[0][0x08 / 4] == 0, "terminal state");
    require(moved_read == total && moved_write == total, "incomplete transfer");
    require(reads == (total + sw - 1) / sw && writes == (total + dw - 1) / dw,
            "access count");
    require(memcmp(memory, expected, sizeof memory) == 0, "destination/tail guards");
}

int main(int argc, char **argv)
{
    int selected = argc > 1 ? atoi(argv[1]) : 0;
    if (selected == 0 || selected == 1) run_case(4, 4, 5, 1, true, true, 0, 0, 0);
    if (selected == 0 || selected == 2) run_case(4, 1, 512, 2, true, false, 0, 0, 1);
    if (selected == 0 || selected == 3) run_case(1, 4, 10, 2, false, true, 0, 0, 2);
    if (selected == 0 || selected == 4) run_case(4, 4, 7, 2, true, false, 0, 0, 3);
    if (selected == 0)
        for (unsigned s = 1; s <= 4; s *= 2)
            for (unsigned d = 1; d <= 4; d *= 2)
                for (unsigned count = 1; count <= 9; count++)
                    for (unsigned sl = 0; sl < 4; sl += s)
                        for (unsigned dl = 0; dl < 4; dl += d) {
                            for (unsigned mode = 0; mode < 4; mode++)
                                run_case(s, d, count, 1, mode & 1, mode & 2, sl, dl, 0);
                            run_case(s, d, count, 2, true, false, sl, dl, 0);
                            run_case(s, d, count, 2, false, true, sl, dl, 0);
                        }
    printf("PASS donor DMA C count: %u cases, exact read/write extents and memory guards\n", cases);
    return 0;
}
