#!/usr/bin/env bash
# Generate rtl/cpu/arm925t_gen.v, the Verilog-2005 netlist of the CPU that
# Quartus 17 compiles, from rtl/cpu/arm925t.sv, the V2 CPU (rtl/cpu/arm9v2,
# with arm9/arm9_alu.sv) and the caches, MMU and writeback in rtl/cpu/zap.
#
#   tools/gen_cpu.sh [OUTPUT]     default OUTPUT: rtl/cpu/arm925t_gen.v
#
# Quartus 17 cannot read this SystemVerilog, so sv2v (https://github.com/
# zachjs/sv2v) converts it, with SYNTHESIS defined (no simulation trace), and
# then this fix is applied:
#   sv2v writes an empty generate branch as "begin ; end", which Quartus
#      17 rejects; the lone ";" is removed (an empty begin-end is legal).
# `make cpu-gen-check` regenerates into a temporary file and compares, so
# the committed file must be regenerated after any change to these sources.
set -euo pipefail
cd "$(dirname "$0")/.."

out=${1:-rtl/cpu/arm925t_gen.v}

if ! command -v sv2v >/dev/null; then
	echo "gen_cpu.sh: sv2v not found (brew install sv2v)" >&2
	exit 1
fi

srcs=(rtl/cpu/arm925t.sv rtl/cpu/arm9/*.sv rtl/cpu/arm9v2/*.sv rtl/cpu/zap/*.sv)

tmp=$(mktemp "${TMPDIR:-/tmp}/gen_cpu.XXXXXX")
trap 'rm -f "$tmp"' EXIT

sv2v -DSYNTHESIS -I rtl/cpu/zap --top=arm925t "${srcs[@]}" > "$tmp"

{
	cat <<'EOF'
// Generated by tools/gen_cpu.sh from rtl/cpu/arm925t.sv, rtl/cpu/zap,
// rtl/cpu/arm9 and rtl/cpu/arm9v2 with sv2v. Do not edit; change the sources and regenerate.
//
// ZAP: Copyright (C) 2016-2024 Revanth Kamaraj (krevanth)
// <revanth91kamaraj@gmail.com>. Changes for the N-Gage QD core: see
// rtl/cpu/zap/NOTICE and docs/CPU.md.
//
// This program is free software; you can redistribute it and/or modify it
// under the terms of the GNU General Public License as published by the Free
// Software Foundation; either version 3 of the License, or (at your option)
// any later version. This program is distributed in the hope that it will be
// useful, but WITHOUT ANY WARRANTY; without even the implied warranty of
// MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE. See the GNU General
// Public License (rtl/cpu/zap/LICENSE) for more details.
//
EOF
	echo "// sv2v $(sv2v --numeric-version)"
	perl -0777 -pe 's/(begin(?: : \w+)?\n)[ \t]*;[ \t]*\n([ \t]*end\b)/$1$2/g' "$tmp"
} > "$out"
