/*
 * The UPP_WD2 flash scrambler: the cellular software (NOS) is stored scrambled
 * in CS0 and the ASIC decodes it on array reads, one 16-bit word at a time.
 * With c the stored word and a its byte address in CS0, plaintext bit i is
 *
 *   c[i] ^ c[j(i)] ^ k(i) ^ parity(a & amask(i)) ^ (a[q0] & a[q1]) ^ (a[q2] & a[q3])
 *
 * The formulas are Andrea Bogazzi's, worked out for the N-Gage (NEM-4) and
 * published in his core (rtl/ngage_descramble.v, GPL-2.0); they decode the
 * N-Gage QD's firmware as well. tools/nos_scramble.py has the evidence and
 * generates the tables below (--emit-c); rtl/mem/ddram_flash.sv is the core's
 * copy. The scrambled area is named by the flash image: the words at CS0
 * 0x174 (first byte) and 0x178 (the byte after the last).
 *
 * Plain C with no QEMU types: the model (ngage_flash.c), tools/patchcheck
 * and the Verilator benches (sim/harness) all include this file.
 *
 * Copyright (c) 2026 the NGage_MiSTer authors
 * SPDX-License-Identifier: GPL-2.0-or-later
 */
#ifndef HW_ARM_NGAGE_SCRAMBLE_H
#define HW_ARM_NGAGE_SCRAMBLE_H

#include <stdint.h>
#include <stdbool.h>

#define NGAGE_SCR_HDR_FIRST 0x174       /* CS0: first scrambled byte */
#define NGAGE_SCR_HDR_END   0x178       /* CS0: the byte after the last */

/* Generated by tools/nos_scramble.py --emit-c: one entry a plaintext bit. */
static const uint8_t ngage_scr_const[16] = { 0, 0, 0, 1, 0, 1, 1, 1, 1, 0, 0, 1, 1, 1, 0, 0 };
static const uint16_t ngage_scr_cmask[16] = {
    0x0101, 0x0202, 0x0044, 0x0108, 0x0012, 0x8020, 0x0840, 0x00A0, 0x0140, 0x2200, 0x0401, 0x0800, 0x5000, 0x2004, 0x4400, 0x8008
};
static const uint32_t ngage_scr_amask[16] = {
    0x020102, 0x000000, 0x102628, 0x040008, 0x004C84, 0x240188, 0x041042, 0x010802, 0x202204, 0x088012, 0x002280, 0x084980, 0x008122, 0x001004, 0x000006, 0x100444
};
static const uint8_t ngage_scr_pairs[16][4] = {
    { 4, 10, 8, 17 }, { 3, 13, 9, 17 }, { 9, 10, 5, 13 }, { 11, 12, 5, 14 }, { 7, 11, 10, 14 }, { 3, 8, 7, 18 }, { 6, 12, 4, 15 }, { 2, 5, 11, 16 }, { 9, 13, 7, 16 }, { 4, 15, 8, 16 }, { 5, 11, 7, 13 }, { 0, 0, 0, 0 }, { 3, 6, 8, 15 }, { 6, 11, 0, 0 }, { 4, 15, 6, 16 }, { 6, 10, 12, 17 }
};
/* Rows of the inverse of the ciphertext part (for encoding). */
static const uint16_t ngage_scr_unmix[16] = {
    0x0941, 0x2A46, 0x0844, 0x0948, 0x2A56, 0x8968, 0x0840, 0x89E8, 0x0940, 0x2A44, 0x0D41, 0x0800, 0x5D41, 0x2844, 0x4D41, 0x8948
};

static inline unsigned ngage_scr_parity(uint32_t x)
{
    x ^= x >> 16;
    x ^= x >> 8;
    x ^= x >> 4;
    x ^= x >> 2;
    x ^= x >> 1;
    return x & 1;
}

/* What the CPU reads for the stored word c at byte address addr of CS0. */
static inline uint16_t ngage_descramble(uint16_t c, uint32_t addr)
{
    /* bits 1-21; bit 0 is clear, so an unused pair (0, 0) adds nothing */
    uint32_t a = addr & 0x3FFFFE;
    uint16_t p = 0;

    for (int i = 0; i < 16; i++) {
        const uint8_t *q = ngage_scr_pairs[i];
        unsigned b = ngage_scr_const[i] ^ ngage_scr_parity(c & ngage_scr_cmask[i]) ^
                     ngage_scr_parity(a & ngage_scr_amask[i]);

        b ^= (a >> q[0]) & (a >> q[1]) & 1;
        b ^= (a >> q[2]) & (a >> q[3]) & 1;
        p |= b << i;
    }
    return p;
}

/* The reverse: the word flash holds for the CPU to read p at addr. */
static inline uint16_t ngage_scramble(uint16_t p, uint32_t addr)
{
    uint16_t x = p ^ ngage_descramble(0, addr);     /* take the address part off */
    uint16_t c = 0;

    for (int i = 0; i < 16; i++) {
        c |= ngage_scr_parity(x & ngage_scr_unmix[i]) << i;
    }
    return c;
}

/*
 * The scrambled area [*first, *end) a CS0 image names, false when it names
 * none: both words must be whole 4 KB pages inside the chip and in order
 * (an erased header, as in the benches' images, has none).
 */
static inline bool ngage_scr_window(const uint8_t *cs0, uint32_t size, uint32_t *first, uint32_t *end)
{
    const uint8_t *f = cs0 + NGAGE_SCR_HDR_FIRST, *e = cs0 + NGAGE_SCR_HDR_END;
    uint32_t a = f[0] | f[1] << 8 | f[2] << 16 | (uint32_t)f[3] << 24;
    uint32_t b = e[0] | e[1] << 8 | e[2] << 16 | (uint32_t)e[3] << 24;

    if (size <= NGAGE_SCR_HDR_END + 3 || (a & 0xFFF) || (b & 0xFFF) || a >= b || b > size) {
        return false;
    }
    *first = a;
    *end = b;
    return true;
}

/* In place over [addr, addr + len): addr and len even. */
static inline void ngage_descramble_buf(uint8_t *d, uint32_t addr, uint32_t len)
{
    for (uint32_t i = 0; i + 1 < len; i += 2) {
        uint16_t p = ngage_descramble(d[i] | d[i + 1] << 8, addr + i);

        d[i] = p;
        d[i + 1] = p >> 8;
    }
}

static inline void ngage_scramble_buf(uint8_t *d, uint32_t addr, uint32_t len)
{
    for (uint32_t i = 0; i + 1 < len; i += 2) {
        uint16_t c = ngage_scramble(d[i] | d[i + 1] << 8, addr + i);

        d[i] = c;
        d[i + 1] = c >> 8;
    }
}

#endif
